from pathlib import Path
import pandas as pd
import numpy as np
import torch
from torch.utils.data import DataLoader, TensorDataset

def find_lobster_files(data_dir: Path, ticker: str = "AMZN", level: int = 10) -> tuple[Path, Path]:
    """
    Locate the message and orderbook files for a given stock
    """
    data_dir = Path(data_dir).expanduser()

    pattern = f"{ticker}_2012-06-21_34200000_57600000_message_{level}.csv"
    matches = sorted(data_dir.rglob(pattern))

    if len(matches) != 1: 
        raise FileNotFoundError(
            f"Expected 1 file matching {pattern} in {data_dir}, found {len(matches)}: {matches}")

    msg_path = matches[0] # location of message file
    ob_path = msg_path.with_name(msg_path.name.replace("message", "orderbook")) # location of orderbook file

    if not ob_path.exists():
        raise FileNotFoundError(
            f"Expected orderbook file {ob_path} to exist, but it does not")

    return msg_path, ob_path

def load_raw(msg_path: Path, ob_path: Path, level: int = 10) -> pd.DataFrame:
    """
    Load the raw message and orderbook files into a single DataFrame
    """
    msg_cols = ["time", "type", "order_id", "size", "price", "direction"]
    
    ob_cols = [] # Bid/ask 1 to 10 levels, each updated on an event (from message file)
    for lev in range(1, level + 1):
        ob_cols += [f"ask_p{lev}", f"ask_s{lev}", f"bid_p{lev}", f"bid_s{lev}"]

    msg = pd.read_csv(msg_path, header=None, names=msg_cols)
    ob = pd.read_csv(ob_path, header=None, names=ob_cols)

    if len(msg) != len(ob): # Ensure message and orderbook have the same number of rows
       raise ValueError(f"Row mismatch: {len(msg)} messages vs {len(ob)} orderbook rows")

    lob = pd.concat([msg, ob], axis=1) # Join message and orderbook side by side

    return lob

def check_invariants(lob: pd.DataFrame, level: int =10) -> dict:
    """
    Check that the data obeys the invariants we want TimeGAN to learn.
    Also used to verify synthetic data generated by TimeGAN. 
    """
    dummy_ask = 9_999_999_999
    dummy_bid = -9_999_999_999

    n = len(lob) 
    report = {}

    crossed = (lob["ask_p1"] <= lob["bid_p1"]) # check if best bid ever >= best ask
    report["crossed"] = int(crossed.sum())

    ask_bad = pd.Series(False, index=lob.index)
    for i in range(1, level):
        ask_bad |= lob[f"ask_p{i+1}"] <= lob[f"ask_p{i}"]
    report["ask_ladder"] = int(ask_bad.sum()) # check if ask prices strictly increase

    bid_bad = pd.Series(False, index=lob.index)
    for i in range(1, level):
        bid_bad |= lob[f"bid_p{i+1}"] >= lob[f"bid_p{i}"]
    report["bid_ladder"] = int(bid_bad.sum()) # check if bid prices strictly decrease

    size_cols = [c for c in lob.columns if "_s" in c]
    neg_size = (lob[size_cols] < 0).any(axis=1) 
    report["neg_size"] = int(neg_size.sum()) # check if any book sizes are 0 or negative

    report["dummy_levels"] = int(((lob[[f"ask_p{i}" for i in range(1, level + 1)]] == dummy_ask).any(axis=1)
                                  | (lob[[f"bid_p{i}" for i in range(1, level + 1)]] == dummy_bid).any(axis=1)).sum())

    any_bad = crossed | ask_bad | bid_bad | neg_size
    report["rows_violating"] = int(any_bad.sum())
    report["frac_violating"] = float(any_bad.mean())
    report["n_rows"] = n

    return report

def build_features(lob: pd.DataFrame, freq: str = "5s", start_s: float = 35100,
                   end_s: float = 56700, level: int = 10):
    """Turn the event-time book into regular-interval model features.

    1. Resample: the book at time T is the last state at or before T; empty intervals are forward-filled.
    2. Features per step: log mid return, spread and level gaps in ticks (all >= 1 in
       valid books), and log(1 + size) per level.
    3. Trim to [start_s, end_s] (seconds after midnight). Features are computed before
       trimming, so the first return uses the mid just before start_s.
    Returns (features, mid); mid is kept only to rebuild prices later, not as a model input.
    """
    TICK = 100

    # 1. Resample to a clock grid. label/closed="right" puts each interval's last state
    #    at the END of the interval, so no value comes from the future (no look-ahead).
    t = pd.Timestamp("2012-06-21") + pd.to_timedelta(lob["time"], unit="s")   # real session date
    lob = lob.set_index(t)
    g = lob.resample(freq, label="right", closed="right").last().ffill()

    # 2. Features
    mid = (g["ask_p1"] + g["bid_p1"]) / 2
    f = pd.DataFrame(index=g.index)
    f["ret"] = np.log(mid).diff()                                 # spec: log returns
    f["spread"] = (g["ask_p1"] - g["bid_p1"]) / TICK
    for i in range(1, level):
        f[f"ask_gap{i}"] = (g[f"ask_p{i+1}"] - g[f"ask_p{i}"]) / TICK
        f[f"bid_gap{i}"] = (g[f"bid_p{i}"] - g[f"bid_p{i+1}"]) / TICK
    for i in range(1, level + 1):
        f[f"ask_logv{i}"] = np.log1p(g[f"ask_s{i}"])              # spec: volume normalisation
        f[f"bid_logv{i}"] = np.log1p(g[f"bid_s{i}"])

    # 3. Trim last, so every row in the window has a valid previous mid
    day = pd.Timestamp("2012-06-21")
    keep = (f.index >= day + pd.to_timedelta(start_s, unit="s")) & (f.index <= day + pd.to_timedelta(end_s, unit="s"))

    return f[keep], mid[keep]

def split_and_normalise(features: pd.DataFrame, train_end_s: float = 49500, val_end_s: float = 53100):
    """
    Split the data into train, validation, and test sets in chronological order
    Train: first 67% of the data - rounds to whole hours when first and last 15 minutes are trimmed.
    Validate: next 17% of 
    Test: last 17% of the data
    4-1-1 hours split
    """
    day = features.index[0].normalize()                       # midnight of the data's own date
    t_train = day + pd.to_timedelta(train_end_s, unit="s")
    t_val = day + pd.to_timedelta(val_end_s, unit="s")
    train = features[features.index < t_train]
    val = features[(features.index >= t_train) & (features.index < t_val)]
    test = features[features.index >= t_val]

    mean = train.mean()
    std = train.std() + 1e-8                 # epsilon guards against a constant column
    norm = lambda df: (df - mean) / std

    return norm(train), norm(val), norm(test), {"mean": mean, "std": std}

def make_windows(df: pd.DataFrame, seq_len: int = 24, stride: int = 1) -> torch.Tensor:
    """Cut one split into overlapping windows of shape (n_windows, seq_len, n_features).

    Called per split, so no window ever crosses a train/val/test boundary.
    """
    x = torch.tensor(df.to_numpy(), dtype=torch.float32)          # (steps, features)
    # unfold slides a window of seq_len along dim 0 -> (n_windows, features, seq_len)
    return x.unfold(0, seq_len, stride).permute(0, 2, 1).contiguous()


def get_data(data_dir, ticker: str = "AMZN", seq_len: int = 24, batch_size: int = 128,
             freq: str = "5s", level: int = 10):
    """Full pipeline: LOBSTER files -> features -> split/normalise -> windows.

    Returns (train_loader, val_windows, test_windows, stats). Train windows are
    shuffled for training (safe: all of them come from the training period);
    val/test are returned whole for evaluation.
    """
    msg_path, ob_path = find_lobster_files(data_dir, ticker, level)
    lob = load_raw(msg_path, ob_path, level)
    features, _ = build_features(lob, freq=freq, level=level)
    train, val, test, stats = split_and_normalise(features)

    train_loader = DataLoader(TensorDataset(make_windows(train, seq_len)),
                              batch_size=batch_size, shuffle=True, drop_last=True)
                              
    return train_loader, make_windows(val, seq_len), make_windows(test, seq_len), stats